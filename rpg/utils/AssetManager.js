// Astra — Asset Manager
//
// Single source of truth for image lookups, lore, and stats.
// Every command that wants to display an item/monster/pet/etc.
// goes through here so adding an image or a line of lore is one
// change, not 20.
//
// Layout on disk:
//   assets/images/items/<rarity>/<name>.png
//   assets/images/pets/<key>.png
//   assets/images/monsters/<name>.png
//   assets/images/bosses/<name>.png
//   assets/images/artifacts/<name>.png
//   assets/images/classes/<tier>/<name>.png
//   assets/images/skins/<rarity>/<key>.png
//
// Fallback chain (no image): render a colored card with emoji
// and stats text. The bot never goes silent just because art
// hasn't been generated yet.
// ═══════════════════════════════════════════════════════════════

'use strict';

const fs = require('fs');
const path = require('path');

const ASSET_ROOT = path.join(__dirname, '..', '..', 'assets', 'images');

// ── Cache: { key: { path, exists, mtime } } ──────────────────
const _cache = new Map();

function safeExists(p) {
  try { return fs.existsSync(p); } catch (_) { return false; }
}

// Resolve an image path. Returns absolute path or null.
function findImage(relativePath) {
  const abs = path.isAbsolute(relativePath) ? relativePath : path.join(ASSET_ROOT, relativePath);
  if (_cache.has(abs)) return _cache.get(abs);
  const exists = safeExists(abs);
  const result = { path: abs, exists };
  _cache.set(abs, result);
  return result;
}

// Invalidate the cache (call after generating a new image).
function invalidateCache(key) {
  if (key) _cache.delete(key);
  else _cache.clear();
}

// ── Slugify: turn "Wooden Club" → "wooden_club" ─────────────
function slugify(name) {
  return String(name)
    .toLowerCase()
    .replace(/['"`]/g, '')
    .replace(/[^a-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '');
}

