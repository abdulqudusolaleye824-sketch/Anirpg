// Get lore for any entity. `kind` is one of:
//   'item' | 'monster' | 'boss' | 'pet' | 'artifact' | 'class'
function getLore(name, kind, extra = {}) {
  if (kind === 'item') {
    return LORE.items[name] || generateItemLore(name, extra.rarity || 'common');
  }
  if (kind === 'monster' || kind === 'boss') {
    return LORE.monsters[name] || generateMonsterLore(name);
  }
  if (kind === 'pet') {
    return LORE.pets[name] || `A small companion — ${name.replace(/_/g, ' ')} — that follows its bonded hunter everywhere.`;
  }
  if (kind === 'artifact') {
    return LORE.artifacts[name] || generateArtifactLore(name);
  }
  if (kind === 'class') {
    return LORE.classes[name] || generateClassLore(name);
  }
  return '';
}

// Format a rarity tag for display
function rarityTag(rarity) {
  const c = ITEM_RARITY_COLORS[rarity] || ITEM_RARITY_COLORS.common;
  return `${c.emoji} *${rarity.toUpperCase()}*`;
}

// Card builder — returns the TEXT block for the second message
// in a two-message card. Caller is responsible for sending the
// image first, then this text.
function buildCardText({ name, kind, rarity, stats, lore, extra }) {
  const lines = [];
  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  if (rarity) lines.push(`${rarityTag(rarity)}  ${name}`);
  else        lines.push(`*${name}*`);
  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  lines.push('');
  if (kind === 'item' || kind === 'artifact') {
    if (stats) {
      const statKeys = Object.keys(stats).filter((k) => stats[k] != null && stats[k] !== 0);
      if (statKeys.length) {
        const statStr = statKeys
          .map((k) => `\`${k.toUpperCase()}\` +${stats[k]}`)
          .join('  ');
        lines.push(`📊 ${statStr}`);
      }
    }
  }
  if (kind === 'monster' || kind === 'boss') {
    if (extra?.level)    lines.push(`📈 Level: *${extra.level}*`);
    if (extra?.hp)       lines.push(`❤️ HP: *${extra.hp.toLocaleString()}*`);
    if (extra?.atk)      lines.push(`⚔️ ATK: *${extra.atk.toLocaleString()}*`);
    if (extra?.def)      lines.push(`🛡️ DEF: *${extra.def.toLocaleString()}*`);
    if (extra?.abilities) lines.push(`💥 Abilities: ${extra.abilities.join(', ')}`);
  }
  if (kind === 'class') {
    if (extra?.tier)   lines.push(`🎖️ Tier: *${extra.tier.toUpperCase()}*`);
    if (extra?.skills) lines.push(`⚡ Skills: ${extra.skills.join(', ')}`);
  }
  lines.push('');
  if (lore) lines.push(`📜 *Lore:*\n${lore}`);
  lines.push('━━━━━━━━━━━━━━━━━━━━━━━━━━━');
  return lines.join('\n');
}

// Look up the image path for a given entity.
// Returns { path, exists } so the caller can decide whether
// to send the image, send a fallback card, or skip.
function getImage({ kind, name, rarity, tier }) {
  let entry;
  switch (kind) {
    case 'item':     entry = getItemImagePath(name, rarity || 'common'); break;
    case 'pet':      entry = getPetImagePath(name); break;
    case 'monster':  entry = getMonsterImagePath(name); break;
    case 'boss':     entry = getBossImagePath(name); break;
    case 'artifact': entry = getArtifactImagePath(name); break;
    case 'class':    entry = getClassImagePath(name, tier || 'common'); break;
    case 'skin':     entry = getSkinImagePath(name, rarity || 'common'); break;
    default: entry = { path: null, exists: false };
  }
  return entry;
}

