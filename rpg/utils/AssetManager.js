function getItemImagePath(name, rarity) {
  const slug = slugify(name);
  return findImage(path.join('items', rarity, `${slug}.png`));
}

// ── 2. Pet lookup ────────────────────────────────────────────
function getPetImagePath(key) {
  return findImage(path.join('pets', `${key}.png`));
}

// ── 3. Monster lookup ────────────────────────────────────────
function getMonsterImagePath(name) {
  return findImage(path.join('monsters', `${slugify(name)}.png`));
}

// ── 4. Boss lookup ───────────────────────────────────────────
function getBossImagePath(name) {
  return findImage(path.join('bosses', `${slugify(name)}.png`));
}

// ── 5. Artifact lookup ───────────────────────────────────────
function getArtifactImagePath(name) {
  return findImage(path.join('artifacts', `${slugify(name)}.png`));
}

// ── 6. Class lookup ──────────────────────────────────────────
function getClassImagePath(name, tier) {
  return findImage(path.join('classes', tier, `${slugify(name)}.png`));
}

// ── 7. Skin lookup ───────────────────────────────────────────
function getSkinImagePath(key, rarity) {
  return findImage(path.join('skins', rarity, `${key}.png`));
}

