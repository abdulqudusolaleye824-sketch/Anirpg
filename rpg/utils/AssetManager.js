function generateMonsterLore(name) {
  const opener = MONSTER_OPENERS[Math.floor(Math.random() * MONSTER_OPENERS.length)].replace('{name}', name);
  const element = detectElement(name);
  const elementLine = element
    ? ` Inherently ${element}-aligned — resists that element, weak to its opposite.`
    : '';
  const pack = /\b(wolf|rat|goblin|orc|bat|spider|serpent|slime|imp|drake|elemental|elf)\b/i.test(name)
    ? ' Hunts in groups. Alone, it is a nuisance; in a pack, it is a slaughter.'
    : ' Prefers to engage targets alone. Possibly because it knows what it is.';
  return `${opener}${elementLine}${pack}`;
}

function generateArtifactLore(name) {
  const opener = `The ${name} — `;
  const lines = [
    'one of the relics the first hunters brought back from the inner gates.',
    'a weapon that has decided, over the centuries, who deserves to wield it.',
    'a fragment of a world that ended before humanity was a thought.',
    'a gift from a god who, having given it, immediately regretted the choice.',
  ];
  return opener + lines[Math.floor(Math.random() * lines.length)];
}

function generateClassLore(name) {
  const opener = `The ${name} — `;
  const lines = [
    'a calling chosen by those who refuse to be one thing.',
    'a path that selects its students, not the other way around.',
    'a discipline passed down in hidden halls and unspoken oaths.',
    'a way of war that everyone respects, even its enemies.',
  ];
  return opener + lines[Math.floor(Math.random() * lines.length)];
}

